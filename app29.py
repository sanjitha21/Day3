#list of list, list of tuple, list of dict example
# A list of lists is a list where each element is itself a list. This allows for the creation of multi-dimensional data structures, such as matrices or grids.
# Example:
matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]   
print(matrix)
# A list of tuples is a list where each element is a tuple. Tuples are immutable sequences, and using them in a list allows for the storage of fixed-size collections of items.
# Example:
matrix = [(
    (1, 2, 3),
    (4, 5, 6),
    (7, 8, 9)
)]
print(matrix)
# example list of dictionary
matrix = [(
    {'n1':'1'},
    {'n2':'4'},
    {'n3':'7'}
)]
print(matrix)